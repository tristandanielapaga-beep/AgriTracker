CREATE TABLE IF NOT EXISTS crops (
    crop_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name TEXT UNIQUE NOT NULL,
    category TEXT NOT NULL CHECK (category IN (
        'Grains', 'Vegetables', 'Fruits', 'Root Crops / Tubers', 'Legumes / Pulses'
    )),
    min_growth_days INTEGER NOT NULL CHECK (min_growth_days > 0),
    max_growth_days INTEGER NOT NULL CHECK (max_growth_days >= min_growth_days),
    preferred_sub_season TEXT NOT NULL CHECK (preferred_sub_season IN (
        'Cool Dry', 'Hot Dry', 'Wet', 'Year-Round'
    ))
);

CREATE TABLE IF NOT EXISTS locations (
    location_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_name TEXT UNIQUE NOT NULL,
    field_type TEXT NOT NULL CHECK (field_type IN (
        'Irrigated Lowland', 'Rainfed Upland', 'Greenhouse/Controlled'
    )),
    area_hectares DOUBLE PRECISION NOT NULL CHECK (area_hectares > 0)
);

CREATE TABLE IF NOT EXISTS production_records (
    record_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id INTEGER NOT NULL REFERENCES crops(crop_id) ON DELETE RESTRICT,
    location_id INTEGER NOT NULL REFERENCES locations(location_id) ON DELETE RESTRICT,
    planting_date DATE NOT NULL,
    target_min_harvest_date DATE NOT NULL,
    target_max_harvest_date DATE NOT NULL,
    actual_harvest_date DATE,
    predicted_yield_kg DOUBLE PRECISION NOT NULL CHECK (predicted_yield_kg >= 0),
    actual_yield_kg DOUBLE PRECISION NOT NULL DEFAULT 0.0 CHECK (actual_yield_kg >= 0),
    yield_variance_pct DOUBLE PRECISION NOT NULL DEFAULT 0.0,
    total_expenses_php DOUBLE PRECISION NOT NULL DEFAULT 0.0 CHECK (total_expenses_php >= 0),
    status TEXT NOT NULL CHECK (status IN ('In Progress', 'Completed', 'Cancelled')),
    is_historical SMALLINT NOT NULL DEFAULT 0 CHECK (is_historical IN (0, 1)),
    CONSTRAINT completed_record_has_harvest_date
        CHECK (status <> 'Completed' OR actual_harvest_date IS NOT NULL)
);

CREATE TABLE IF NOT EXISTS production_expenses (
    expense_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id INTEGER NOT NULL REFERENCES production_records(record_id) ON DELETE CASCADE,
    expense_category TEXT NOT NULL CHECK (expense_category IN (
        'Seeds/Seedlings', 'Fertilizer/Soil Inputs', 'Pesticides/Crop Protection',
        'Labor/Workforce', 'Fuel/Irrigation/Utilities', 'Equipment/Maintenance', 'Other'
    )),
    description TEXT NOT NULL,
    amount_php DOUBLE PRECISION NOT NULL CHECK (amount_php > 0),
    date_logged DATE NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_production_records_crop_id ON production_records(crop_id);
CREATE INDEX IF NOT EXISTS idx_production_records_location_id ON production_records(location_id);
CREATE INDEX IF NOT EXISTS idx_production_records_status ON production_records(status);
CREATE INDEX IF NOT EXISTS idx_production_records_harvest_date ON production_records(actual_harvest_date);
CREATE INDEX IF NOT EXISTS idx_production_expenses_record_id ON production_expenses(record_id);
